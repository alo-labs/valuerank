"""Wall-clock access with an override for reproducible builds.

Every generator stamps the observation instant into its output. Set the
``VALUERANK_NOW`` environment variable to an ISO 8601 instant (for example
``2026-10-07T17:23:20Z``) to make all stages use that instant instead of the
current time, which lets the committed publication be regenerated byte for byte.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone

ENV_VAR = "VALUERANK_NOW"


def utcnow() -> datetime:
    """Return the current UTC instant, or the pinned ``VALUERANK_NOW`` instant."""

    raw = os.environ.get(ENV_VAR, "").strip()
    if not raw:
        return datetime.now(timezone.utc)
    try:
        parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(f"{ENV_VAR} must be an ISO 8601 instant, got {raw!r}") from exc
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def iso_z(moment: datetime | None = None) -> str:
    """Format an instant as whole-second UTC with a ``Z`` suffix."""

    if moment is None:
        moment = utcnow()
    return moment.replace(microsecond=0).isoformat().replace("+00:00", "Z")
